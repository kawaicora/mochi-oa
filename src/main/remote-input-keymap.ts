/** 查表并在缺失时给出可读原因（调用方负责记日志） */
export function mapKey(
  table: Record<number, number>,
  keyCode: number,
  platformLabel: string
): { ok: true; code: number } | { ok: false; reason: string } {
  if (!Number.isFinite(keyCode) || keyCode <= 0) return { ok: false, reason: `非法 keyCode=${keyCode}` }
  const code = table[keyCode]
  if (code == null) return { ok: false, reason: `keyCode=${keyCode} 未收录到 ${platformLabel} 键码表` }
  return { ok: true, code }
}
